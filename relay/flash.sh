#!/usr/bin/env bash
# Build and flash relay.ino with secrets from ../.env.
#
# Writes relay/secrets.h (gitignored) from RELAY_SECRET, RELAY_WIFI_SSID and
# RELAY_WIFI_PASSWORD, then compiles and uploads with arduino-cli.
#
#   relay/flash.sh                 # auto-detect the USB serial port
#   PORT=/dev/cu.usbserial-0001 relay/flash.sh
#   FQBN=esp32:esp32:esp32 relay/flash.sh
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
root="$(dirname "$here")"
FQBN="${FQBN:-esp32:esp32:esp32}"

# Parse .env with python-dotenv, the same parser the Python services use, so
# quoting and escaping behave the same on both ends.
uv run --project "$root/monitor" python - "$root/.env" "$here/secrets.h" <<'PY'
import json, sys
from dotenv import dotenv_values

env = dotenv_values(sys.argv[1])
keys = ["RELAY_SECRET", "RELAY_WIFI_SSID", "RELAY_WIFI_PASSWORD"]
missing = [k for k in keys if not env.get(k)]
if missing:
    sys.exit(f"Missing in {sys.argv[1]}: {', '.join(missing)}")

lines = ["// Generated by relay/flash.sh from .env. Do not commit.", "#pragma once"]
for k in keys:
    # A JSON string is also a valid C string literal.
    lines.append(f"#define {k} {json.dumps(env[k], ensure_ascii=False)}")
with open(sys.argv[2], "w") as f:
    f.write("\n".join(lines) + "\n")
PY

if [ -z "${PORT:-}" ]; then
  PORT="$(ls /dev/cu.usbserial-* /dev/cu.SLAB_USBtoUART* /dev/cu.wchusbserial* \
    /dev/cu.usbmodem* /dev/ttyUSB* /dev/ttyACM* 2>/dev/null | head -n1 || true)"
  if [ -z "$PORT" ]; then
    echo "No ESP32 serial port found. Plug it in or set PORT=/dev/cu.…" >&2
    exit 1
  fi
fi

echo "Flashing $FQBN on $PORT"
arduino-cli compile --fqbn "$FQBN" --upload --port "$PORT" "$here"
